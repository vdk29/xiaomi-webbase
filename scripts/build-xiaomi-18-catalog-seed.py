"""Build the reviewed, idempotent catalogue data update; never import stock."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
models = json.loads((root / 'supabase/data/xiaomi-18-global-specs-20261118.json').read_text())
images = json.loads((root / 'supabase/data/xiaomi-18-global-images-20261118.json').read_text())
sql = '''-- Generated by scripts/build-xiaomi-18-catalog-seed.py from reviewed source manifests.
-- Storage uploads must be independently checksum-verified before applying this update.
-- No product creation, deletion, SKU, stock, price, or demo-state changes.
begin;
do $seed$
declare p record; f jsonb; i jsonb; m text[]; inventory_before text; products_before bigint;
begin
 select md5(coalesce(string_agg(to_jsonb(s)::text,'' order by product_id),'')) into inventory_before from public.webbase_stock s;
 select count(*) into products_before from public.webbase_products;
 for i in select value from jsonb_array_elements($images$IMAGES$images$::jsonb) loop
  if not exists(select 1 from public.webbase_products where id=(i->>'product_id')::uuid and sku=i->>'sku' and model=i->>'model' and color=i->>'color' and not is_demo) then
   raise exception 'Photo target identity changed: %',i->>'sku';
  end if;
  if not exists(select 1 from storage.objects where bucket_id='webbase-products' and name=i->>'path' and (metadata->>'size')::int=(i->>'byte_size')::int) then
   raise exception 'Verified Storage object missing: %',i->>'path';
  end if;
  insert into public.webbase_product_images(id,product_id,storage_path,sort_order,is_primary,mime_type,byte_size,width,height,original_name,source_url)
  values((i->>'id')::uuid,(i->>'product_id')::uuid,i->>'path',(i->>'sort_order')::int,(i->>'is_primary')::boolean,'image/webp',(i->>'byte_size')::int,(i->>'width')::int,(i->>'height')::int,i->>'original_name',i->>'source_url')
  on conflict(storage_path) do nothing;
 end loop;
 for f in select value from jsonb_array_elements($models$MODELS$models$::jsonb) loop
  for p in select * from public.webbase_products where model=f->>'model' for update loop
   -- Do not silently overwrite a specification edited manually since preparation.
   if p.updated_by is not null then raise exception 'Review administrator edits before updating %',p.id;end if;
   if p.specs->>'_catalog_update' is distinct from 'xiaomi-18-global-20261118' and
    exists(select 1 from jsonb_object_keys(coalesce(p.specs,'{}')) k where left(k,1)<>'_' and k not in ('Встроенная память (ГБ)','Оперативная память (ГБ)')) then
    raise exception 'Review existing manual specifications before updating %',p.id;
   end if;
   m:=regexp_match(p.memory,'([0-9]+)[[:space:]]*/[[:space:]]*([0-9]+)');
   if m is null or p.color not in ('black','white','blue','red') then raise exception 'Unknown target variant %',p.id;end if;
   update public.webbase_products set
    description=case when coalesce(description,'')='' then f->>'description' else description end,
    specs=coalesce(specs,'{}')||(f->'specs')||jsonb_build_object(
     'Оперативная память (ГБ)',m[1]::int,'Встроенная память (ГБ)',m[2]::int,
     'Размеры',f->'dimensions'->>(case when p.color='blue' then 'blue' else 'base' end),
     'Вес',f->'weight'->>(case when p.color='blue' then 'blue' else 'base' end),
     'Цвет',case p.color when 'black' then 'Чёрный (Black)' when 'white' then 'Белый (White)' when 'blue' then 'Синий глянцевый (Cosmic Blue)' when 'red' then 'Красный (Velvet Red)' end)
   where id=p.id;
   insert into public.webbase_network_sources(product_id,kind,url,details)
   select p.id,'manufacturer_specs',f->'specs'->>'_source_url',jsonb_build_object('update','xiaomi-18-global-20261118','region','Global','verified_at','2026-11-18')
   where not exists(select 1 from public.webbase_network_sources where product_id=p.id and kind='manufacturer_specs' and url=f->'specs'->>'_source_url');
   if (select count(*) from public.webbase_product_images where product_id=p.id)+
      (select count(*) from public.webbase_shared_product_images(array[p.id]))<>3 then raise exception 'Expected three photo angles for %',p.id;end if;
   update public.webbase_network_jobs set status='done',photo_found=true,description_found=true,reason=null,lease_until=null,updated_at=now() where product_id=p.id;
  end loop;
 end loop;
 if inventory_before is distinct from (select md5(coalesce(string_agg(to_jsonb(s)::text,'' order by product_id),'')) from public.webbase_stock s) then raise exception 'Inventory changed';end if;
 if products_before<>(select count(*) from public.webbase_products) then raise exception 'Catalogue identities changed';end if;
end $seed$;
commit;
'''.replace('IMAGES', json.dumps(images, ensure_ascii=False)).replace('MODELS', json.dumps(models, ensure_ascii=False))
(root / 'supabase/seed_xiaomi_18_global_20261118.sql').write_text(sql)
